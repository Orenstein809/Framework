package utils;

public class UrlMethode {

    private String url;
    private String methode;

    public void setUrl(String url) {
        this.url = url;
    }

    public void setMethode(String methode) {
        this.methode = methode;
    }

    public String getUrl() {
        return this.url;
    }

    public String getMethode() {
        return this.methode;
    }

}
